package ru.practicum.mainservice.clients;

import com.sun.net.httpserver.HttpExchange;
import com.sun.net.httpserver.HttpServer;
import io.github.resilience4j.circuitbreaker.CircuitBreaker;
import io.github.resilience4j.circuitbreaker.CircuitBreakerRegistry;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import ru.practicum.common.dto.EventInternalDto;
import ru.practicum.common.enums.EventState;
import ru.practicum.common.exception.ServiceUnavailableException;
import ru.practicum.mainservice.CommentServiceApplication;

import java.io.IOException;
import java.net.InetSocketAddress;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.concurrent.CopyOnWriteArrayList;
import java.util.concurrent.atomic.AtomicBoolean;
import java.util.concurrent.atomic.AtomicInteger;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * Exercises the real Spring Cloud OpenFeign proxy and its Resilience4j circuit breaker.
 * The downstream is an in-process HTTP stub; neither Docker nor PostgreSQL is used.
 */
@SpringBootTest(classes = CommentServiceApplication.class,
        webEnvironment = SpringBootTest.WebEnvironment.NONE)
@ActiveProfiles("test")
class EventServiceFeignCircuitBreakerIntegrationTest {
    private static final long eventId = 999999L;
    private static final AtomicBoolean available = new AtomicBoolean(false);
    private static final AtomicInteger httpRequests = new AtomicInteger();
    private static final HttpServer stubServer = createServer();

    @Autowired
    private EventServiceClient client;

    @Autowired
    private CircuitBreakerRegistry registry;

    @DynamicPropertySource
    static void configure(DynamicPropertyRegistry properties) {
        properties.add("spring.cloud.openfeign.client.config.event-service.url",
                () -> "http://127.0.0.1:" + stubServer.getAddress().getPort());
        properties.add("spring.cloud.openfeign.circuitbreaker.enabled", () -> "true");
        properties.add("resilience4j.circuitbreaker.configs.default.sliding-window-type", () -> "COUNT_BASED");
        properties.add("resilience4j.circuitbreaker.configs.default.sliding-window-size", () -> "2");
        properties.add("resilience4j.circuitbreaker.configs.default.minimum-number-of-calls", () -> "2");
        properties.add("resilience4j.circuitbreaker.configs.default.failure-rate-threshold", () -> "50");
        properties.add("resilience4j.circuitbreaker.configs.default.wait-duration-in-open-state", () -> "250ms");
        properties.add("resilience4j.circuitbreaker.configs.default.permitted-number-of-calls-in-half-open-state",
                () -> "2");
    }

    @AfterAll
    static void stopStub() {
        stubServer.stop(0);
    }

    @Test
    void feignFallbackOpensCircuitAndClosesItAfterRecovery() throws InterruptedException {
        // A real HTTP 503 is intentionally generated by the local downstream stub.
        assertThatThrownBy(() -> client.getEvent(eventId))
                .isInstanceOf(ServiceUnavailableException.class);

        CircuitBreaker circuitBreaker = registry.getAllCircuitBreakers().stream()
                .filter(item -> item.getName().contains("EventServiceClient")
                        && item.getName().contains("getEvent"))
                .findFirst()
                .orElseThrow(() -> new AssertionError("Feign circuit breaker was not registered"));
        assertThat(circuitBreaker.getState()).isEqualTo(CircuitBreaker.State.CLOSED);

        List<String> transitions = new CopyOnWriteArrayList<>();
        circuitBreaker.getEventPublisher().onStateTransition(event ->
                transitions.add(event.getStateTransition().toString()));

        assertThatThrownBy(() -> client.getEvent(eventId))
                .isInstanceOf(ServiceUnavailableException.class);
        assertThat(circuitBreaker.getState()).isEqualTo(CircuitBreaker.State.OPEN);

        // An OPEN circuit must reject the request without calling the downstream.
        int requestsBeforeRejection = httpRequests.get();
        assertThatThrownBy(() -> client.getEvent(eventId))
                .isInstanceOf(ServiceUnavailableException.class);
        assertThat(httpRequests.get()).isEqualTo(requestsBeforeRejection);

        // When the local downstream recovers, half-open probes should close the circuit.
        available.set(true);
        Thread.sleep(600);
        EventInternalDto firstProbe = client.getEvent(eventId);
        EventInternalDto secondProbe = client.getEvent(eventId);
        assertThat(firstProbe.getId()).isEqualTo(eventId);
        assertThat(secondProbe.getState()).isEqualTo(EventState.PUBLISHED);
        assertThat(circuitBreaker.getState()).isEqualTo(CircuitBreaker.State.CLOSED);
        assertThat(transitions).contains(
                "State transition from CLOSED to OPEN",
                "State transition from OPEN to HALF_OPEN",
                "State transition from HALF_OPEN to CLOSED");
    }

    private static HttpServer createServer() {
        try {
            HttpServer server = HttpServer.create(new InetSocketAddress("127.0.0.1", 0), 0);
            server.createContext("/internal/events/", EventServiceFeignCircuitBreakerIntegrationTest::respond);
            server.start();
            return server;
        } catch (IOException exception) {
            throw new IllegalStateException("Could not start local Feign test stub", exception);
        }
    }

    private static void respond(HttpExchange exchange) throws IOException {
        httpRequests.incrementAndGet();
        try {
            if (!available.get()) {
                exchange.sendResponseHeaders(503, -1);
                return;
            }
            byte[] response = ("{\"id\":" + eventId + ",\"state\":\"PUBLISHED\"}")
                    .getBytes(StandardCharsets.UTF_8);
            exchange.getResponseHeaders().add("Content-Type", "application/json");
            exchange.sendResponseHeaders(200, response.length);
            exchange.getResponseBody().write(response);
        } finally {
            exchange.close();
        }
    }
}
